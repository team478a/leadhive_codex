import { execFileSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { test, expect } from '@playwright/test'

test('Human can review, defer, approve and revoke a DM in company detail without sending', async ({ page }) => {
  test.setTimeout(120_000)
  const python = process.env.PYTHON || (process.platform === 'win32' ? '../backend/.venv/Scripts/python.exe' : '../backend/.venv/bin/python')
  const env = { ...process.env, E2E_EMAIL: `e2e-inline-${randomBytes(8).toString('hex')}@example.com`, E2E_PASSWORD: randomBytes(24).toString('hex') }
  execFileSync(python, ['../backend/tests/e2e_user.py', 'create'], { env })
  const forbidden: string[] = []
  page.on('request', request => {
    if (!['localhost', '127.0.0.1'].includes(new URL(request.url()).hostname) || /\/(?:send|dispatch|execute|test-send)(?:[/?]|$)/.test(request.url())) forbidden.push(request.url())
  })
  try {
    const fixture = JSON.parse(execFileSync(python, ['../backend/tests/e2e_user.py', 'destination-selection-fixture'], { env, encoding: 'utf8' })) as { project_id: string }
    await page.goto('/')
    await page.getByLabel('メールアドレス').fill(env.E2E_EMAIL)
    await page.getByLabel('パスワード').fill(env.E2E_PASSWORD)
    await page.getByRole('button', { name: 'ログインする', exact: true }).click()
    await page.getByRole('dialog', { name: '3ステップで始めましょう' }).getByRole('button', { name: 'あとで見る' }).click()
    const menuButton = page.getByRole('button', { name: /メニュー/ })
    if (await menuButton.isVisible()) await menuButton.click()
    await page.getByRole('navigation', { name: 'メインナビゲーション' }).getByRole('button', { name: '▤ 企業一覧', exact: true }).click()
    await page.getByRole('combobox', { name: 'プロジェクト', exact: true }).selectOption(fixture.project_id)
    await page.getByRole('button', { name: '詳細', exact: true }).first().click()
    const panel = page.getByRole('region', { name: 'リスト完成の根拠' })
    await panel.getByRole('button', { name: 'プロジェクトの窓口候補を整理', exact: true }).click()
    const assessment = panel.getByRole('region', { name: '窓口の利用可否と理由' })
    await assessment.locator('summary').click()
    await assessment.getByRole('combobox', { name: '窓口用途', exact: true }).selectOption('business')
    await assessment.getByRole('combobox', { name: '窓口の対象範囲', exact: true }).selectOption('company')
    await assessment.getByLabel('用途の根拠URL', { exact: true }).fill('https://approval.example/contact')
    await assessment.getByLabel('公開ページの用途説明', { exact: true }).fill('事業提携などのご相談はこちらで受け付けます。')
    await assessment.getByRole('button', { name: '用途確認を記録', exact: true }).click()
    const choice = assessment.getByRole('region', { name: '営業準備に使う窓口の選択' })
    await choice.getByRole('button', { name: /この窓口を準備対象に選択/ }).click()
    const dm = panel.getByRole('region', { name: '根拠付きDM下書き準備' })
    await dm.getByText('基本文面テンプレートを作成', { exact: true }).click()
    await dm.getByLabel('基本文面の名前', { exact: true }).fill('Synthetic evidence template')
    await dm.getByLabel('基本文面の件名', { exact: true }).fill('Synthetic subject')
    await dm.getByLabel('サービス説明・提案・CTA・署名', { exact: true }).fill('サービスのご紹介です。ご関心がありましたらご返信ください。Synthetic Sender')
    await dm.getByRole('button', { name: '基本文面を登録', exact: true }).click()
    await expect(dm.getByRole('combobox', { name: 'DMの基本文面', exact: true })).toContainText('Synthetic evidence template')
    await dm.getByLabel('個別情報の根拠URL', { exact: true }).fill('https://approval.example/services')
    await dm.getByLabel('確認した公開情報の引用', { exact: true }).fill('当社は公開のサービス紹介を掲載しています。')
    await dm.getByLabel('DMに使う事実', { exact: true }).fill('公開のサービス紹介を掲載しています')
    await dm.getByLabel('この公式ページで事実と引用を確認しました', { exact: true }).check()
    await dm.getByRole('button', { name: '根拠付き下書きを保存', exact: true }).click()
    const saved = dm.getByRole('article', { name: '保存した根拠付き下書き' })
    const handoff = saved.getByRole('region', { name: 'DM承認準備' })
    await handoff.getByRole('button', { name: '入力内容を確認', exact: true }).click()
    await expect(handoff).toContainText('入力確認済み・提案作成前')
    await handoff.getByRole('button', { name: '承認待ち提案を準備', exact: true }).click()
    await expect(handoff).toContainText('提案状態：PENDING')
    await handoff.getByRole('button', { name: 'この画面で内容を確認・承認', exact: true }).click()
    const review = handoff.getByRole('region', { name: 'DMの確認と承認' })
    await expect(review).toContainText(`recipient-${fixture.project_id.replaceAll('-', '')}@example.com`)
    await expect(review).toContainText('公開のサービス紹介を掲載しています')
    await expect(review.getByRole('button', { name: /予約|送信$/ })).toHaveCount(0)
    await review.getByRole('button', { name: '保留・確認を終了', exact: true }).click()
    await expect(handoff).toContainText('提案状態：PENDING')
    await handoff.getByRole('button', { name: 'この画面で内容を確認・承認', exact: true }).click()
    await review.getByLabel('承認用パスワード（再認証）').fill('wrong-password')
    await review.getByRole('button', { name: '内容を確認して承認', exact: true }).click()
    await expect(review.getByRole('alert')).toContainText('再認証に失敗')
    await review.getByLabel('承認用パスワード（再認証）').fill(env.E2E_PASSWORD)
    await review.getByRole('button', { name: '内容を確認して承認', exact: true }).click()
    await expect(review.getByRole('status')).toContainText('送信は行っていません')
    await expect(handoff).toContainText('提案状態：APPROVED')
    await review.getByLabel('却下・取消の理由').fill('Human review deferred')
    await review.getByRole('button', { name: '取消', exact: true }).click()
    await expect(handoff).toContainText('提案状態：REVOKED')
    const deliveries = await page.request.get(`/api/projects/${fixture.project_id}/email-deliveries`)
    expect(deliveries.ok()).toBeTruthy()
    expect((await deliveries.json() as { items: unknown[] }).items).toEqual([])
    expect(forbidden).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  } finally {
    execFileSync(python, ['../backend/tests/e2e_user.py', 'cleanup'], { env })
  }
})
